"""Generate plugin files from src/agent_cairn/assets so agent-facing text has one source (D10).

Writes skills/<name>/SKILL.md, and the version in .claude-plugin/plugin.json and
package.json. With --check,
writes nothing and exits 1 if a committed file differs from what would be generated (R11.7).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agent_cairn import __version__, integrations  # noqa: E402 - needs the src path above
from agent_cairn.constants import SKILL_NAMES  # noqa: E402

HEADER = "<!-- generated by scripts/gen_plugin.py from src/agent_cairn/assets — do not edit -->"
MANIFEST = ROOT / ".claude-plugin" / "plugin.json"
PACKAGE = ROOT / "package.json"
PRE_RELEASE = re.compile(r"^(\d+\.\d+\.\d+)\.?(dev|a|b|rc)(\d+)$")


def expected_files() -> dict[Path, str]:
    """Return every generated file and its content."""
    files = {
        ROOT / "skills" / name / "SKILL.md": integrations.skill_text(name, header=HEADER)
        for name in SKILL_NAMES
    }
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    manifest["version"] = __version__
    files[MANIFEST] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    package = json.loads(PACKAGE.read_text(encoding="utf-8"))
    package["version"] = npm_version(__version__)
    files[PACKAGE] = json.dumps(package, indent=2, ensure_ascii=False) + "\n"
    return files


def npm_version(version: str) -> str:
    """Turn a Python version into npm's semver: ``0.2.0.dev0`` -> ``0.2.0-dev.0``."""
    match = PRE_RELEASE.match(version)
    if match is None:
        return version
    release, label, number = match.groups()
    return f"{release}-{label}.{number}"


def main(argv: list[str] | None = None) -> int:
    """Write the generated files, or with --check report the stale ones."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if anything is out of date")
    args = parser.parse_args(argv)
    stale = [
        path
        for path, text in expected_files().items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for path in stale:
            sys.stderr.write(f"out of date: {path.relative_to(ROOT)} (run make gen)\n")
        return 1 if stale else 0
    for path, text in expected_files().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
