"""Generate plugin files from src/agent_cairn/assets so agent-facing text has one source (D10).

Writes skills/<name>/SKILL.md and the version in .claude-plugin/plugin.json. With --check,
writes nothing and exits 1 if a committed file differs from what would be generated (R11.7).
"""

from __future__ import annotations

import argparse
import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agent_cairn import __version__, assets  # noqa: E402 - needs the src path above

HEADER = "<!-- generated by scripts/gen_plugin.py from src/agent_cairn/assets — do not edit -->"
MANIFEST = ROOT / ".claude-plugin" / "plugin.json"
WIDTH = 96


def frontmatter(meta: dict[str, str]) -> str:
    """Render skill frontmatter; the description is folded so the file stays readable."""
    lines = ["---"]
    for key, value in meta.items():
        if key == "description":
            lines.append(f"{key}: >-")
            lines += textwrap.wrap(value, WIDTH, initial_indent="  ", subsequent_indent="  ")
        elif any(ch in value for ch in "[]:#"):
            lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
        else:
            lines.append(f"{key}: {value}")
    return "\n".join([*lines, "---"]) + "\n"


def expected_files() -> dict[Path, str]:
    """Return every generated file and its content."""
    skills = json.loads((assets.ASSETS_DIR / "skills.json").read_text(encoding="utf-8"))
    template = (assets.ASSETS_DIR / "template.md").read_text(encoding="utf-8")
    files = {
        ROOT / "skills" / name / "SKILL.md": frontmatter(meta)
        + HEADER
        + "\n"
        + assets.fill(f"skill_{name}.md", template=template)
        for name, meta in skills.items()
    }
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    manifest["version"] = __version__
    files[MANIFEST] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    return files


def main(argv: list[str] | None = None) -> int:
    """Write the generated files, or with --check report the stale ones."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if anything is out of date")
    args = parser.parse_args(argv)
    stale = [
        path
        for path, text in expected_files().items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for path in stale:
            sys.stderr.write(f"out of date: {path.relative_to(ROOT)} (run make gen)\n")
        return 1 if stale else 0
    for path, text in expected_files().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
